// 获取当前语言
function getCurrentLanguage() {
    return localStorage.getItem('selectedLanguage') || 'en';
}

// 设置语言
function setLanguage(lang) {
    localStorage.setItem('selectedLanguage', lang);
    switchLanguage(lang); // 保证所有内容和按钮都同步
}

// 切换语言
function switchLanguage(lang) {
    localStorage.setItem('selectedLanguage', lang);

    // 更新所有带有 data-i18n 属性的元素
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });

    // 更新所有带有 data-i18n-placeholder 属性的元素
    document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
        const key = element.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });

    // 更新所有语言切换按钮的显示文本
    const languageNames = {
        'en': 'English',
        'zh': '中文',
        'ja': '日本語',
        'ko': '한국어',
        'fr': 'Français'
    };
    document.querySelectorAll('.current-language').forEach(element => {
        element.textContent = languageNames[lang];
    });
}

// 页面加载时应用保存的语言设置，并绑定按钮事件
// 只保留一个DOMContentLoaded
document.addEventListener('DOMContentLoaded', function() {
    const savedLanguage = getCurrentLanguage();
    switchLanguage(savedLanguage);
    // 绑定语言切换按钮
    document.querySelectorAll('.language-switcher .dropdown-item').forEach(button => {
        button.addEventListener('click', function(e) {
            e.preventDefault();
            const lang = this.getAttribute('onclick').match(/'([^']+)'/)[1];
            switchLanguage(lang);
        });
    });
}); 